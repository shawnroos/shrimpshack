#!/usr/bin/env python3
import json
import subprocess
import sys
from pathlib import Path

PEEK = Path(__file__).resolve().parent.parent
EXAMPLES = PEEK / 'skills/peek-recipes/examples'
FIXTURE = PEEK / 'tests/fixtures/skill-examples.ts'
SHAPE = PEEK / 'tests/fixtures/plugin-shape.ts'
SHAPE_KEYS = ('name', 'model', 'tools')
LINKS = {
    'notion-pages': 'https://www.notion.so/Onboarding-guide-1f2e3d4c5b6a47988a9b0c1d2e3f4a5b',
    'youtube-videos': 'https://www.youtube.com/watch?v=aqz-KE-bpKQ&t=95s',
}


def load(path: Path):
    return json.loads(path.read_text())


def fixture() -> str:
    entries = []
    for id, link in sorted(LINKS.items()):
        entry = {'id': id, 'link': link, 'recipe': load(EXAMPLES / id / 'recipe.json'), 'page': load(EXAMPLES / f'{id}.page.json')}
        sample = EXAMPLES / f'{id}.sample.json'
        if sample.exists():
            entry['sample'] = sample.read_text()
        entries.append(json.dumps(entry, indent=2, ensure_ascii=True))
    body = ',\n'.join(entries)
    return (
        '// Generated by tests/mirror-skill-examples.py from skills/peek-recipes/examples: the test sandbox cannot read JSON files, so edit an example and run that script, never this file.\n'
        "import type { Page } from '../../hooks/recipes/page'\n\n"
        'type Example = { id: string; link: string; recipe: { source: Record<string, unknown> } & Record<string, unknown>; page: Page; sample?: string }\n\n'
        f'export const EXAMPLES: Example[] = [\n{body},\n]\n'
    )


def frontmatter(path: Path) -> dict:
    lines = path.read_text().split('\n')
    if lines[0] != '---' or '---' not in lines[1:]:
        raise SystemExit(f'{path.relative_to(PEEK)}: no frontmatter')
    found = {}
    for line in lines[1:lines.index('---', 1)]:
        key, sep, value = line.partition(': ')
        if sep and key in SHAPE_KEYS:
            found[key] = json.loads(value) if key == 'tools' else value
    return found


def shape() -> str:
    agents = [{'file': path.relative_to(PEEK).as_posix(), **frontmatter(path)} for path in sorted((PEEK / 'agents').glob('*.md'))]
    data = {
        'agents': agents,
        'skillNames': sorted(path.parent.name for path in (PEEK / 'skills').glob('*/SKILL.md')),
        'skill': (PEEK / 'skills/peek-recipes/SKILL.md').read_text(),
        'agentBodies': {path.stem: path.read_text() for path in sorted((PEEK / 'agents').glob('*.md'))},
    }
    return (
        '// Generated by tests/mirror-skill-examples.py from agents/ and skills/: the test sandbox cannot read markdown files, so edit those and run that script, never this file.\n'
        'type Agent = { file: string; name?: string; model?: string; tools?: string[] }\n\n'
        f'export const SHAPE: {{ agents: Agent[]; skillNames: string[]; skill: string; agentBodies: Record<string, string> }} = {json.dumps(data, indent=2, ensure_ascii=True)}\n'
    )


def output_problems() -> list[str]:
    problems = []
    for id, link in LINKS.items():
        source = load(EXAMPLES / id / 'recipe.json')['source']
        argv = source.get('run') or source.get('map')
        folder = EXAMPLES / id
        sample = EXAMPLES / f'{id}.sample.json'
        stdin = sample.read_text() if 'map' in source else None
        if 'map' in source and not stdin:
            problems.append(f'{id}: an MCP example needs {sample.name}, the tool result saved in the map stdin shape')
            continue
        out = subprocess.run([str(folder / argv[0]), *argv[1:], link], cwd=folder, input=stdin, capture_output=True, text=True, env={'PATH': '/usr/bin:/bin', 'PEEK_URL': link}, check=False)
        try:
            page = json.loads(out.stdout)
        except json.JSONDecodeError:
            page = None
        if out.returncode != 0 or page != load(EXAMPLES / f'{id}.page.json'):
            what = f'the map run on {sample.name}' if stdin else f'the script output for {link}'
            problems.append(f'{id}: {what} differs from {id}.page.json (exit {out.returncode}) {out.stderr.strip()}')
    return problems


def main() -> int:
    wanted = {FIXTURE: fixture(), SHAPE: shape()}
    if '--check' not in sys.argv:
        for path, text in wanted.items():
            path.write_text(text)
        return 0
    problems = output_problems()
    for path, text in wanted.items():
        if not path.exists() or path.read_text() != text:
            problems.append(f'{path.relative_to(PEEK)} is out of date: run tests/mirror-skill-examples.py')
    for problem in problems:
        print(problem, file=sys.stderr)
    if not problems:
        print('skill examples: fixtures match, and the script and the map on its sample print their sample pages')
    return 1 if problems else 0


sys.exit(main())
