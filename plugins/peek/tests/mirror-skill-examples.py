#!/usr/bin/env python3
import json
import subprocess
import sys
from pathlib import Path

PEEK = Path(__file__).resolve().parent.parent
EXAMPLES = PEEK / 'skills/peek-recipes/examples'
FIXTURE = PEEK / 'tests/fixtures/skill-examples.ts'
LINKS = {
    'acme-wiki': 'https://wiki.acme.example/pages/onboarding',
    'youtube-videos': 'https://www.youtube.com/watch?v=aqz-KE-bpKQ&t=95s',
}


def load(path: Path):
    return json.loads(path.read_text())


def fixture() -> str:
    entries = []
    for id, link in sorted(LINKS.items()):
        entry = {'id': id, 'link': link, 'recipe': load(EXAMPLES / id / 'recipe.json'), 'page': load(EXAMPLES / f'{id}.page.json')}
        entries.append(json.dumps(entry, indent=2, ensure_ascii=True))
    body = ',\n'.join(entries)
    return (
        '// Generated by tests/mirror-skill-examples.py from skills/peek-recipes/examples: the test sandbox cannot read JSON files, so edit an example and run that script, never this file.\n'
        "import type { Page } from '../../hooks/page'\n\n"
        'type Example = { id: string; link: string; recipe: { source: Record<string, unknown> } & Record<string, unknown>; page: Page }\n\n'
        f'export const EXAMPLES: Example[] = [\n{body},\n]\n'
    )


def script_output_problems() -> list[str]:
    problems = []
    for id, link in LINKS.items():
        recipe = load(EXAMPLES / id / 'recipe.json')
        run = recipe['source'].get('run')
        if not run:
            continue
        folder = EXAMPLES / id
        out = subprocess.run([str(folder / run[0]), *run[1:], link], cwd=folder, capture_output=True, text=True, env={'PATH': '/usr/bin:/bin', 'PEEK_URL': link}, check=False)
        if out.returncode != 0 or json.loads(out.stdout) != load(EXAMPLES / f'{id}.page.json'):
            problems.append(f'{id}: the script output for {link} differs from {id}.page.json (exit {out.returncode})')
    return problems


def main() -> int:
    wanted = fixture()
    if '--check' not in sys.argv:
        FIXTURE.write_text(wanted)
        return 0
    problems = script_output_problems()
    if FIXTURE.read_text() != wanted:
        problems.append(f'{FIXTURE.relative_to(PEEK)} is out of date: run tests/mirror-skill-examples.py')
    for problem in problems:
        print(problem, file=sys.stderr)
    if not problems:
        print('skill examples: fixture and script output match')
    return 1 if problems else 0


sys.exit(main())
