#!/usr/bin/env bash
set -uo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
AUTO_ROOT="$(cd "${SCRIPT_DIR}/../.." && pwd)"
SWEEP="${AUTO_ROOT}/skills/programme-sweep/SKILL.md"
JUDGE="${AUTO_ROOT}/skills/programme-sweep/references/judgment.md"
TRACK="${AUTO_ROOT}/skills/programme-tracker/SKILL.md"

PASS=0
FAIL=0
CURRENT="anonymous"
it()   { CURRENT="${1:-anonymous}"; }
pass() { PASS=$((PASS + 1)); printf "  \033[32m✓\033[0m %s\n" "$CURRENT"; }
fail() { FAIL=$((FAIL + 1)); printf "  \033[31m✗\033[0m %s\n" "$CURRENT"; [ -n "${1:-}" ] && printf "      %s\n" "$1"; return 0; }
has() { case "$2" in *"$1"*) pass ;; *) fail "expected to find [$1]" ;; esac; }
lacks() { case "$2" in *"$1"*) fail "did not expect [$1]" ;; *) pass ;; esac; }

echo "programme-sweep-skill.test.sh"
S="$(cat "$SWEEP")"
J="$(cat "$JUDGE")"
T="$(cat "$TRACK")"

it "the sweep has a When to speak rule that ends a quiet sweep with no chat text"
has "## When to speak" "$S"
has "end the sweep with no chat text at all" "$S"
it "an ask is posted once per facts fingerprint and marked shown"
has "P ask-shown <item> --fingerprint <fp>" "$S"
it "the sweep never tells the PM to end with a Next: line"
has 'never end a message with a "Next:" line' "$S"
it "plain words that point to one ask approve nothing and get the exact reply"
has "record nothing and relay nothing" "$S"
it "the PM records before it relays and marks the relay"
has "Record, then relay." "$S"
has "P ask-relayed <item>" "$S"
it "step 16 no longer re-arms the remit watcher every sweep"
lacks "so re-arming is safe" "$S"
has "Do not arm it on" "$S"
it "step 17 runs the stop self-check on actionable reasons"
has "programme.actionable_reasons" "$S"
it "the sub-agent ground rule no longer claims a sub-agent has its own session id"
lacks "a sub-agent has its own session id" "$S"
it "the reporting rules name everything, restate state and carry the contract checklist"
has "**Name everything.**" "$J"
has "**Restate the state.**" "$J"
has "**Show the contract checklist**" "$J"
has "P check-mergeable <pr> --pin <item>" "$J"
it "the tracker voice allows PR and issue numbers with titles and bans herdr codes"
has "Name a PR or issue with its title beside its" "$T"
has "herdr item codes" "$T"

DOMAIN="$(cat "${AUTO_ROOT}/skills/programme-sweep/references/domain.md" 2>/dev/null)"
it "the sweep names its four stages in order and points to domain.md"
has "Four stages: domain check (1 to 5, 5b), remit sessions (6 to 11), outside" "$S"
has "references/domain.md" "$S"
it "steps 5b, 11b and 11c exist without renumbering the 17 steps"
has "5b. **Domain check.**" "$S"
has "11b. **Outside sessions.**" "$S"
has "11c. **Domain check again.**" "$S"
has "17. **Check, then stop.**" "$S"
it "domain.md carries the order, the close rule and the recommend-only rule"
has "rank 0 \`needs_shawn\`" "$DOMAIN"
has "only when the folder is gone, the item's PR is merged and the" "$DOMAIN"
has "You only recommend." "$DOMAIN"
has "P recommendations-shown --fingerprint" "$DOMAIN"

CHECKS="$(cat "${AUTO_ROOT}/skills/programme-sweep/references/checks.md" 2>/dev/null)"
it "the sweep points to checks.md, which states the code routes and where hooks run from"
has "references/checks.md" "$S"
has "P record-hook-patch" "$S"
has "Code by PR and publish" "$CHECKS"
has "A patch to the installed copy" "$CHECKS"
has "A change reaches workers only after publish and reload." "$CHECKS"
has "neither route bypasses them" "$CHECKS"
it "the sweep names the standing clause as a refusal of an Auto limit"
has "a refusal of an Auto limit" "$S"
lacks "a blocked command" "$S"

OWN="$(cat "${AUTO_ROOT}/skills/programme-sweep/references/own-words.md" 2>/dev/null)"
it "the sweep points to own-words.md, and a decline in his own words runs nothing"
has "references/own-words.md" "$S"
has "\"No\", \"Skip r1\" and \"Keep item-x\" on a drop picker are declines" "$OWN"
has "Run nothing" "$OWN"
has "--reads-as" "$OWN"
it "own-words.md keeps the authority moves on a pick and the suggestion out"
has "Relay his words and ask again" "$OWN"
has "An accepted suggestion approves no offer" "$OWN"
has "Show the \`read_back\` line to Shawn" "$OWN"

it "the PM is told to offer permission allow, and the fix lines name it"
has "--command 'answer-permission <perm-id> allow'" "$S"
has "answer-permission <perm-id> allow\\|not-now\\|no --prompt <id>" "$S"
SETTLE="$(cat "${AUTO_ROOT}/lib/programme_permission_settle.py")"
has "offer answer-permission {proposal['id']} allow again" "$SETTLE"
has "offer answer-permission {proposal['id']} allow to arm" "$SETTLE"

CK="$(cat "${AUTO_ROOT}/skills/programme-sweep/references/checks.md")"
it "checks.md shows the whole set-check usage and how wide an off reaches"
has 'P set-check <name> on|off [--item <id> | --own] [--prompt <id>]' "$CK"
has '`--item <id> off` frees one item; a programme `off` frees every item' "$CK"
it "checks.md says when the PM lifts a limit, when it keeps it, and to tell Shawn about a lift of his limit"
has "Lift a limit when the refused call is needed for the item's next product check" "$CK"
has "Otherwise keep it" "$CK"
has "tell him in one line" "$CK"
it "checks.md gives one channel for a refused worker: the journal and its transcript, not an ask"
has "you see the refusal in the journal and the worker's transcript" "$CK"
lacks "the worker asks you to lift it" "$CK"
it "checks.md tells the PM to prompt a running worker after a set-check, both ways"
has "carries the limit lines by itself" "$CK"
has "say in the text which limit is off" "$CK"
it "judgment.md R4 sends a check limit to checks.md"
has "A check limit is not a restriction: it follows [checks.md](checks.md)" "$J"
it "sweep step 9 sends a limit refusal to checks.md, not to Shawn"
has 'A hook refusal on an item with a `limit_refused` journal row' "$S"
has 'is a check limit: [references/checks.md](references/checks.md), not Shawn.' "$S"
it "the sweep says what to do with limits_not_briefed"
has '`limits_not_briefed`' "$S"

echo "programme-sweep-skill.test.sh: ${PASS} passed, ${FAIL} failed"
[ "$FAIL" -eq 0 ]
